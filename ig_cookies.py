from __future__ import annotations

import re
from pathlib import Path
from urllib.parse import unquote

from settings import HOME

COOKIES_NAME = "instagram_cookies.txt"
SESSION_DEAD = (
    "Session Instagram sudah tidak valid / kedaluwarsa. "
    "Tempel sessionid baru dari browser lalu Simpan session."
)


def cookies_path() -> Path:
    return HOME / COOKIES_NAME


def _sessionid_value(path: Path) -> str:
    if not path.is_file():
        return ""
    try:
        text = path.read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return ""
    for line in text.splitlines():
        if line.startswith("#") or not line.strip():
            continue
        parts = line.split("\t")
        if len(parts) >= 7 and parts[5] == "sessionid":
            return parts[6].strip()
    return ""


def _has_session(path: Path) -> bool:
    return bool(_sessionid_value(path))


def status() -> dict:
    path = cookies_path()
    ready = _has_session(path)
    return {
        "logged_in": ready,
        "path": str(path),
        "message": "Instagram sudah login." if ready else "Belum login Instagram.",
    }


def clear_cookies() -> dict:
    path = cookies_path()
    if path.exists():
        path.unlink()
    return status()


def _cookie_line(
    name: str,
    value: str,
    domain: str = ".instagram.com",
    path_value: str = "/",
    secure: bool = True,
    expires: int = 0,
) -> str:
    domain = (domain or ".instagram.com").strip() or ".instagram.com"
    if not domain.startswith("."):
        domain = "." + domain.lstrip(".")
    include_subdomains = "TRUE" if domain.startswith(".") else "FALSE"
    return "\t".join(
        [
            domain,
            include_subdomains,
            path_value or "/",
            "TRUE" if secure else "FALSE",
            str(max(int(expires or 0), 0)),
            name,
            value,
        ]
    )


def _normalize_session_value(raw: str) -> str:
    value = (raw or "").strip().strip('"').strip("'")
    if value.lower().startswith("sessionid="):
        value = value.split("=", 1)[1].strip()
    # Drop trailing junk if user pasted "value;" or "value csrftoken=..."
    if ";" in value:
        value = value.split(";", 1)[0].strip()
    if "%3A" in value.upper():
        value = unquote(value)
    return value.strip()


def _parse_cookie_header(raw: str) -> list[dict]:
    """Parse 'sessionid=...; csrftoken=...; ds_user_id=...' paste."""
    text = (raw or "").strip()
    if not text or "=" not in text or ("sessionid" not in text.lower() and "\t" not in text):
        return []
    if "\t" in text:
        return []
    cookies: list[dict] = []
    for part in text.split(";"):
        part = part.strip()
        if not part or "=" not in part:
            continue
        name, value = part.split("=", 1)
        name = name.strip()
        value = value.strip().strip('"').strip("'")
        if not name:
            continue
        if name.lower() == "sessionid":
            value = _normalize_session_value(value)
        cookies.append(
            {
                "name": name,
                "value": value,
                "domain": ".instagram.com",
                "path": "/",
                "secure": True,
                "expirationDate": 2147483647,
            }
        )
    return cookies


def write_netscape(cookies: list[dict]) -> dict:
    path = cookies_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# Netscape HTTP Cookie File", "# This file was generated by Pinterest Download by GEMADIPADA"]
    names: set[str] = set()
    session_value = ""
    for item in cookies or []:
        name = str(item.get("name") or "").strip()
        value = str(item.get("value") or "")
        if not name:
            continue
        domain = str(item.get("domain") or ".instagram.com").strip() or ".instagram.com"
        if "instagram.com" not in domain:
            continue
        if name == "sessionid":
            value = _normalize_session_value(value)
            session_value = value
        expires = item.get("expirationDate") or item.get("expires") or 0
        try:
            expires_i = int(float(expires))
        except (TypeError, ValueError):
            expires_i = 0
        lines.append(
            _cookie_line(
                name,
                value,
                domain=domain,
                path_value=str(item.get("path") or "/") or "/",
                secure=bool(item.get("secure", True)),
                expires=expires_i,
            )
        )
        names.add(name)

    # gallery-dl / IG API often expect ds_user_id alongside sessionid
    if session_value and "ds_user_id" not in names:
        uid = session_value.split(":", 1)[0]
        if uid.isdigit():
            lines.append(_cookie_line("ds_user_id", uid))

    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    result = status()
    if not result["logged_in"]:
        raise ValueError("Cookie sessionid belum ada. Login Instagram sampai beranda terbuka.")
    result["message"] = "Session tersimpan. Silakan unduh; kalau gagal, tempel sessionid lagi."
    return result


def write_sessionid(sessionid: str, csrftoken: str = "") -> dict:
    raw = (sessionid or "").strip()
    # Full Cookie header paste
    if "sessionid=" in raw.lower() and (";" in raw or raw.lower().count("sessionid=") == 1 and "=" in raw):
        parsed = _parse_cookie_header(raw if "sessionid=" in raw.lower() else f"sessionid={raw}")
        if any(c["name"] == "sessionid" for c in parsed):
            if csrftoken and not any(c["name"] == "csrftoken" for c in parsed):
                token = csrftoken.strip()
                if token.lower().startswith("csrftoken="):
                    token = token.split("=", 1)[1].strip()
                if token:
                    parsed.append(
                        {
                            "name": "csrftoken",
                            "value": token,
                            "domain": ".instagram.com",
                            "path": "/",
                            "secure": True,
                            "expirationDate": 2147483647,
                        }
                    )
            return write_netscape(parsed)

    value = _normalize_session_value(raw)
    if not value:
        raise ValueError("sessionid kosong.")
    if len(value) < 20:
        raise ValueError(
            "sessionid terlalu pendek. Salin nilai cookie sessionid lengkap dari browser "
            "(DevTools → Application → Cookies → sessionid)."
        )
    # Reject values that look truncated (IG sessionid is usually userid:token:count:checksum)
    if value.count(":") < 2 and "%3A" not in value.upper():
        # still allow unusual formats, but warn via length already
        pass
    cookies = [
        {
            "name": "sessionid",
            "value": value,
            "domain": ".instagram.com",
            "path": "/",
            "secure": True,
            "expirationDate": 2147483647,
        }
    ]
    token = (csrftoken or "").strip()
    if token.lower().startswith("csrftoken="):
        token = token.split("=", 1)[1].strip()
    if token:
        cookies.append(
            {
                "name": "csrftoken",
                "value": token,
                "domain": ".instagram.com",
                "path": "/",
                "secure": True,
                "expirationDate": 2147483647,
            }
        )
    return write_netscape(cookies)


def write_netscape_text(raw: str) -> dict:
    text = (raw or "").strip()
    if not text:
        raise ValueError("Cookie kosong.")
    # Cookie header / single sessionid
    if "\t" not in text:
        return write_sessionid(text)
    path = cookies_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    body = text if text.startswith("#") else "# Netscape HTTP Cookie File\n" + text
    if not re.search(r"(^|\t)sessionid(\t|$)", body) and "sessionid" not in body:
        raise ValueError("Teks cookie harus berisi sessionid.")
    path.write_text(body.rstrip() + "\n", encoding="utf-8")
    # Ensure ds_user_id if missing
    sid = _sessionid_value(path)
    if sid:
        uid = sid.split(":", 1)[0]
        if uid.isdigit() and "ds_user_id" not in body:
            with path.open("a", encoding="utf-8") as handle:
                handle.write(_cookie_line("ds_user_id", uid) + "\n")
    result = status()
    if not result["logged_in"]:
        raise ValueError("sessionid tidak ditemukan di cookie yang ditempel.")
    result["message"] = "Session tersimpan. Silakan unduh; kalau gagal, tempel sessionid lagi."
    return result
